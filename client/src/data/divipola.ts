export function buscarMunicipio(query: string): Municipio[] {
  if (!query || query.trim().length < 1) return MUNICIPIOS;
  const q = query.trim().toLowerCase();
  return MUNICIPIOS.filter(
    (m) =>
      m.nombre.toLowerCase().includes(q) ||
      m.codigo.includes(q) ||
      m.departamento.toLowerCase().includes(q)
  );
}

export function getMunicipioByCodigo(codigo: string): Municipio | undefined {
  return MUNICIPIOS.find((m) => m.codigo === codigo);
}
